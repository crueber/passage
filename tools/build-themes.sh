#!/usr/bin/env sh
# Build the Passage theme stylesheet.
#
# Concatenates every internal/web/ui/themes/*.css (sorted by filename) into
# internal/web/static/themes.css, prefixed with a generated-file header.
#
# Themes are plain CSS custom-property overrides, not Tailwind sources — the
# Tailwind CLI cannot compile them, so this script is deliberately trivial and
# deterministic. Same philosophy as build-css.sh: the committed output is
# drift-checked in CI.
#
# Usage:
#   tools/build-themes.sh           # write internal/web/static/themes.css
#   tools/build-themes.sh --check   # exit non-zero if the committed file is stale
set -eu

# Deterministic glob ordering (ASCII, not locale-dependent).
LC_ALL=C
export LC_ALL

cd "$(dirname "$0")/.."

SRC_DIR="internal/web/ui/themes"
OUT="internal/web/static/themes.css"
HEADER="/* generated by tools/build-themes.sh — do not edit */"

if [ ! -d "$SRC_DIR" ]; then
  echo "error: $SRC_DIR not found" >&2
  exit 1
fi

build() {
  printf '%s\n\n' "$HEADER"
  # LC_ALL=C keeps the glob order stable across locales and machines.
  set -- "$SRC_DIR"/*.css
  for f in "$@"; do
    [ -e "$f" ] || continue
    cat "$f"
    printf '\n'
  done
}

case "${1:-}" in
  "")
    build > "$OUT"
    echo "wrote $OUT"
    ;;
  --check)
    tmp="$(mktemp)"
    trap 'rm -f "$tmp"' EXIT INT TERM
    build > "$tmp"
    if ! cmp -s "$tmp" "$OUT"; then
      echo "error: $OUT is out of date — run ./tools/build-themes.sh" >&2
      exit 1
    fi
    echo "$OUT is up to date"
    ;;
  *)
    echo "usage: $0 [--check]" >&2
    exit 2
    ;;
esac
